"""Экономика пакетов и размер выборки для теста спроса.
Затраты звонка — оценка из analysis/unit_economics.py (базовый сценарий 2,19 руб; высокий 8,57 руб).
Пакеты и пороги конверсии — допущения для теста, не факты.
Запуск: python3 -I analysis/test_design.py
"""
COST_BASE, COST_HIGH = 2.19, 8.57

PACKS = [  # (цена руб/мес, звонков в пакете, цена доплаты руб за звонок сверх пакета)
    (149, 30, 3.0),
    (199, 60, 3.0),
]
print("Пакет: ИИ-затраты при полном использовании пакета и маржа от них, %")
for price, n, extra in PACKS:
    for label, c in (("база", COST_BASE), ("высокий", COST_HIGH)):
        cost = n * c
        print(f"  {price} руб, {n} звонков, {label}: затраты {cost:.0f} руб, маржа {(price-cost)/price*100:.0f}%")
print("Доплата 3 руб/звонок покрывает базовую стоимость 2,19 руб (маржа",
      f"{(3-COST_BASE)/3*100:.0f}%), но не высокий сценарий {COST_HIGH} руб")

print("\nРазмер выборки на группу, n ≈ 16·p(1−p)/δ² (5%, мощность 80%, knowledge/experiments.md):")
for p, d in ((0.01, 0.02), (0.02, 0.02), (0.03, 0.02), (0.05, 0.03)):
    n = 16 * p * (1 - p) / d**2
    print(f"  p={p:.2f}, δ={d:.2f}: {n:.0f} человек на группу")
print("\nЧетыре ячейки (2 сообщения × 2 цены), по 1200 показов: около 4800 показов (p=0,03, δ=0,02 -> 1164 на ячейку).")
